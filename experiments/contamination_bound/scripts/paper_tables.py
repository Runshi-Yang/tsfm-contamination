"""Regenerate every table in the paper, and every number the prose quotes, from the result files.

    python -m experiments.contamination_bound.scripts.paper_tables <overleaf>/tables

WHY. The first draft copied numbers from the Step 1-5 report, and some had drifted: group means
computed before the one unverified direct window was dropped, a probe figure from one run quoted
beside a table from another, a cell standard error computed from the controls' spread. Here each
table is built from per-window or per-cell data, the keep mask is applied once, and each table
names the run it comes from. Numbers used in running text are written as LaTeX macros to
`numbers.tex`, so text and tables cannot disagree.

SOURCES (one run per table):
  pool, errors, metric check .... files/scores_chronos-t5-*.npz + keep_mask.npz + pool.npz
  gate .......................... pool.features on the kept windows
  raw bound ..................... files/bound_*.json          adjusted bound ... files/adjust_*.json
  robustness .................... files/robust_*_ce_sum.json  power ........... files/power_*.json
  cross-family control .......... files/famcompare.json
  planted grid, Chronos 46M ..... $CB_OUT/inject_delta_ep10.npz  (the run whose weights the probe
                                  and the detectors use)
  family thresholds ............. files/family_thresholds.json
  Moirai, point losses .......... files/family_moirai-small-point.json
  detectors ..................... files/detect.json          probe ........... files/probe.json
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy import stats

from .pool import load, features, auroc as gate_auroc, inventory, ushcn_corpus_ids, FILES
from .inject import OUT, KS, TYPES

SIZES = [("mini", "20M"), ("small", "46M"), ("base", "201M"), ("large", "709M")]
GROUPS = ["direct", "indirect", "clean"]
FORM = {"verbatim": "exact", "variant": "near-duplicate", "mixup": "blend"}


def f(x, d=2, sign=False):
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("-", "$-$") if not sign else s.replace("-", "$-$").replace("+", "$+$")


def sci(p):
    if p >= 0.001:
        return f"{p:.3f}" if p < 0.1 else f"{p:.2f}"
    m, e = f"{p:.1e}".split("e")
    return f"${m}{{\\times}}10^{{{int(e)}}}$"


class Out:
    def __init__(self, d):
        self.d = Path(d); self.d.mkdir(parents=True, exist_ok=True); self.macros = []

    def table(self, name, body):
        (self.d / f"{name}.tex").write_text(body.strip() + "\n")

    def num(self, name, value):
        # A macro may land in running text or inside $...$, so it must never carry its own dollars.
        if "$" in value or value.lstrip().startswith("-"):
            value = "\\ensuremath{" + value.replace("$", "") + "}"
        self.macros.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def close(self):
        (self.d / "numbers.tex").write_text(
            "% Generated by paper_tables.py. Do not edit by hand.\n" + "\n".join(self.macros) + "\n")


def main(outdir):
    o = Out(outdir)
    keep = np.load(FILES / "keep_mask.npz")["keep"]
    win, grp, sta, corr = load()
    win, grp, sta, corr = win[keep], grp[keep], sta[keep], corr[keep]
    S = {}
    for s, _ in SIZES:
        z = np.load(FILES / f"scores_chronos-t5-{s}.npz", allow_pickle=True)
        S[s] = {k: z[k][keep] for k in z.files if getattr(z[k], "shape", ()) and len(z[k]) == len(keep)}
        assert (S[s]["group"] == grp).all()

    # ------------------------------------------------------------------ pool
    rows = []
    for g in GROUPS:
        m = grp == g
        cc = corr[m]
        ccs = "---" if g == "clean" else f"{np.nanmedian(cc):.3f}"
        dry = float((win[m] <= 0).mean())
        rows.append(f"{g} & {'2010--2014' if g != 'clean' else '2024-06 onward'} & {m.sum()} & "
                    f"{len(np.unique(sta[m]))} & {ccs} & {dry:.3f} \\\\")
        o.num(f"n{g.capitalize()}", str(int(m.sum())))
        o.num(f"st{g.capitalize()}", str(len(np.unique(sta[m]))))
        if g == "indirect":
            o.num("corrIndirect", f"{np.nanmedian(cc):.3f}")   # median, as in FINDINGS
    o.table("pool", "\\begin{tabular}{llrrrr}\n\\toprule\ngroup & period & windows & stations & "
            "\\texttt{corpus\\_corr} & dry days \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}")
    o.num("dryAll", f"{100 * float((win <= 0).mean()):.0f}")

    ver = json.load(open(FILES / "direct_verification.json"))
    o.num("verifiedDirect", str(ver["counts"]["confirmed"]))
    o.num("candidateDirect", str(ver["n_direct"]))

    # distance from each indirect station to the nearest corpus station
    inv, ush = inventory(), ushcn_corpus_ids()
    cx = np.array([inv[s][:2] for s in ush if s in inv])
    def km(a, b):
        la1, lo1, la2, lo2 = map(np.radians, (a[0], a[1], b[:, 0], b[:, 1]))
        h = np.sin((la2 - la1) / 2) ** 2 + np.cos(la1) * np.cos(la2) * np.sin((lo2 - lo1) / 2) ** 2
        return 6371 * 2 * np.arcsin(np.sqrt(h))
    dist = np.array([km(inv[s][:2], cx).min() for s in np.unique(sta[grp == "indirect"]) if s in inv])
    o.num("distMedian", f"{np.median(dist):.0f}")
    o.num("distNinety", f"{np.percentile(dist, 90):.0f}")
    o.num("distMax", f"{dist.max():,.0f}".replace(",", "{,}"))

    # ------------------------------------------------------------------ gate
    F, names = features(win)
    gate = {}
    for pos, neg in [("direct", "indirect"), ("direct", "clean"), ("indirect", "clean")]:
        m = np.isin(grp, [pos, neg]); y = grp[m] == pos
        a = [max(gate_auroc(F[m][:, i], y), 1 - gate_auroc(F[m][:, i], y)) for i in range(F.shape[1])]
        gate[(pos, neg)] = max(a)
    o.num("gateDI", f"{gate[('direct', 'indirect')]:.3f}")
    o.num("gateDC", f"{gate[('direct', 'clean')]:.3f}")
    o.num("gateIC", f"{gate[('indirect', 'clean')]:.3f}")

    # ------------------------------------------------------------------ errors by group, metric check
    rows = []
    for s, lab in SIZES:
        for j, g in enumerate(GROUPS):
            m = grp == g
            vals = [np.nanmean(S[s][k][m]) for k in ("ce_sum", "mase1", "wql", "scrps")]
            head = f"\\multirow{{3}}{{*}}{{{lab}}}" if j == 0 else ""
            rows.append(f"{head} & {g} & {vals[0]:.2f} & {vals[1]:.4f} & {vals[2]:.4f} & {vals[3]:.4f} \\\\")
        if s != "large":
            rows.append("\\midrule")
    o.table("errors", "\\begin{tabular}{llrrrr}\n\\toprule\ncheckpoint & group & CE & MASE & WQL & "
            "sCRPS \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    same = [float((S["mini"]["mase1"] == S[s]["mase1"]).mean()) for s in ("small", "base", "large")]
    o.num("maseSameLo", f"{100 * min(same):.1f}")
    o.num("maseSameHi", f"{100 * max(same):.1f}")
    ctx, hor = win[:, :512].astype(np.float64), win[:, 512:576].astype(np.float64)
    den = np.abs(ctx[:, 1:] - ctx[:, :-1]).mean(1)
    dd = np.abs(hor).mean(1) / den
    o.num("maseZero", f"{np.mean(dd):.4f}")
    o.num("maseSmall", f"{np.nanmean(S['small']['mase1']):.4f}")
    w = S["small"]["wql"]
    o.num("wqlMedian", f"{np.nanmedian(w):.4f}")
    o.num("wqlNear", f"{100 * np.nanmean(np.abs(w - 1) <= 0.01):.0f}")
    sel = np.isin(grp, ["direct", "indirect"])
    for k, name in (("ce_sum", "Ce"), ("scrps", "Scrps"), ("mase1", "Mase")):
        r = np.corrcoef(dd[sel], S["small"][k][sel])[0, 1]
        o.num(f"corrD{name}", f"{r:.3f}"); o.num(f"rsqD{name}", f"{r * r:.2f}")
    o.num("maseDirect", f"{np.nanmean(S['small']['mase1'][grp == 'direct']):.4f}")
    o.num("maseIndirect", f"{np.nanmean(S['small']['mase1'][grp == 'indirect']):.4f}")
    o.num("maseHarder", f"{100 * (np.nanmean(S['small']['mase1'][grp == 'direct']) / np.nanmean(S['small']['mase1'][grp == 'indirect']) - 1):.1f}")
    o.num("ceIndirectCleanGap", f"{np.nanmean(S['small']['ce_sum'][grp == 'indirect']) - np.nanmean(S['small']['ce_sum'][grp == 'clean']):.1f}")

    # ------------------------------------------------------------------ bound
    rows, adj_b, raw_b, gaps, rem = [], [], [], [], []
    for s, lab in SIZES:
        b = json.load(open(FILES / f"bound_chronos-t5-{s}.json"))["direct_vs_indirect/ce_sum"]
        a = json.load(open(FILES / f"adjust_chronos-t5-{s}.json"))["ce_sum"]
        rows.append(f"{lab} & {f(b['diff'], 2, True)} & {b['bound_pct']:.1f}\\% & & {f(a['adj_diff'], 2, True)} & "
                    f"$[{a['adj_lo']:.2f},\\ {a['adj_hi']:.2f}]$ & \\textbf{{{a['adj_bound']:.1f}\\%}} \\\\")
        adj_b.append(a["adj_bound"]); raw_b.append(b["bound_pct"])
        gaps.append(100 * a["adj_diff"] / a["ref_mean"]); rem.append(100 * (1 - a["adj_diff"] / a["raw_diff"]))
        if s == "small":
            o.num("refSmall", f"{b['mean_ref']:.2f}")
            o.num("rawDiffSmall", f"{b['diff']:.2f}")
            o.num("rawLoSmall", f"{b['lo']:.2f}"); o.num("rawHiSmall", f"{b['hi']:.2f}")
            o.num("rawBoundSmall", f"{b['bound_pct']:.1f}")
            o.num("adjDiffSmall", f"{a['adj_diff']:.2f}")
            o.num("adjLoSmall", f"{a['adj_lo']:.2f}")
            o.num("rawWidthSmall", f"{b['hi'] - b['lo']:.1f}")
            o.num("adjWidthSmall", f"{a['adj_hi'] - a['adj_lo']:.1f}")
    o.table("bound", "\\begin{tabular}{lrrcrrr}\n\\toprule\n& \\multicolumn{2}{c}{raw} & & "
            "\\multicolumn{3}{c}{adjusted for difficulty} \\\\\n\\cmidrule(lr){2-3}\\cmidrule(lr){5-7}\n"
            "checkpoint & $\\Delta$ & bound & & $\\beta$ & 95\\% interval & bound \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    o.num("adjBoundLo", f"{min(adj_b):.1f}"); o.num("adjBoundHi", f"{max(adj_b):.1f}")
    o.num("rawBoundLo", f"{min(raw_b):.1f}"); o.num("rawBoundHi", f"{max(raw_b):.1f}")
    o.num("adjGaps", ", ".join(f"{g:.1f}" for g in gaps[:-1]) + f" and {gaps[-1]:.1f}")
    o.num("removedLo", f"{min(rem):.1f}"); o.num("removedHi", f"{max(rem):.1f}")
    a46 = json.load(open(FILES / "adjust_chronos-t5-small.json"))["ce_sum"]
    nats46 = -a46["adj_lo"]                                   # the 46M bound in nats, one checkpoint
    o.num("boundNatsSmall", f"{nats46:.2f}"); o.num("adjBoundSmall", f"{a46['adj_bound']:.1f}")
    o.num("natsPerToken", f"{nats46 / 65:.3f}"); o.num("probGain", f"{100 * (math.exp(nats46 / 65) - 1):.0f}")
    # sCRPS: report its adjusted bound instead of excluding it on correlation alone
    sc = [json.load(open(FILES / f"adjust_chronos-t5-{s_}.json"))["scrps"]["adj_bound"] for s_, _ in SIZES]
    o.num("scrpsAdjLo", f"{min(sc):.1f}"); o.num("scrpsAdjHi", f"{max(sc):.1f}")
    o.num("scrpsAdjBySize", ", ".join(f"{b:.1f}" for b in sc[:-1]) + f" and {sc[-1]:.1f}")
    scr = [json.load(open(FILES / f"adjust_chronos-t5-{s_}.json"))["scrps"]["raw_bound"] for s_, _ in SIZES]
    o.num("scrpsRawLo", f"{min(scr):.1f}"); o.num("scrpsRawHi", f"{max(scr):.1f}")
    # resampling unit: stations vs geographic blocks. The station columns are the reported bounds
    # (bound_*.json, adjust_*.json); the block columns come from blockboot.py.
    bb = json.load(open(FILES / "blockboot.json"))
    rows = []
    for s_, lab in SIZES:
        rb_ = json.load(open(FILES / f"bound_chronos-t5-{s_}.json"))["direct_vs_indirect/ce_sum"]["bound_pct"]
        ab_ = json.load(open(FILES / f"adjust_chronos-t5-{s_}.json"))["ce_sum"]["adj_bound"]
        raw = [rb_, bb[f"{s_}/2deg/raw"]["bound"], bb[f"{s_}/5deg/raw"]["bound"]]
        adj = [ab_, bb[f"{s_}/2deg/adj"]["bound"], bb[f"{s_}/5deg/adj"]["bound"]]
        rows.append(f"{lab} & " + " & ".join(f"{x:.1f}\\%" for x in raw) + " & & "
                    + " & ".join(f"{x:.1f}\\%" for x in adj) + " \\\\")
    nu = [bb[f"small/{u}/adj"]["n_units"] for u in ("station", "2deg", "5deg")]
    o.table("blockboot", "\\begin{tabular}{lrrrcrrr}\n\\toprule\n& \\multicolumn{3}{c}{raw} & & "
            "\\multicolumn{3}{c}{adjusted for difficulty} \\\\\n\\cmidrule(lr){2-4}\\cmidrule(lr){6-8}\n"
            "checkpoint & stations & $2^\\circ$ cells & $5^\\circ$ cells & & stations & $2^\\circ$ cells & "
            "$5^\\circ$ cells \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    for u, nm in (("2deg", "Two"), ("5deg", "Five")):
        v = [bb[f"{s_}/{u}/adj"]["bound"] for s_, _ in SIZES]
        o.num(f"block{nm}Lo", f"{min(v):.1f}"); o.num(f"block{nm}Hi", f"{max(v):.1f}")
    o.num("nStationUnits", str(nu[0])); o.num("nTwoDegUnits", str(nu[1])); o.num("nFiveDegUnits", str(nu[2]))
    # pretraining exposure estimate
    ex = json.load(open(FILES / "exposure_estimate.json"))
    o.num("expDay", f"{ex['day_exposures_unmixed']:.1f}"); o.num("expBlend", f"{ex['day_exposures_in_blends']:.0f}")
    o.num("expExact", f"{ex['exact_window_exposures']:.4f}"); o.num("expOneIn", f"{ex['one_in']:,.0f}".replace(",", "{,}"))
    o.num("drawsPerAug", f"{ex['draws_per_augmentation']:.1f}")
    # binomial intervals and the uncertainty of the control 95th percentile
    from scipy.stats import beta as _b
    o.num("cpZeroTen", f"{_b.ppf(0.975, 1, 10):.2f}"); o.num("cpOneTen", f"{_b.ppf(0.975, 2, 9):.2f}")
    o.num("pNinetyFiveSd", f"{math.sqrt(0.05 * 0.95 / 400):.3f}")

    # ------------------------------------------------------------------ robustness
    rows = []
    for key, name in (("mase0", "$d$ (reported)"), ("horizstd", "horizon s.d."),
                      ("ctxmae", "context variability"), ("dryfrac", "dry-day share")):
        r = [json.load(open(FILES / f"robust_chronos-t5-{s}_ce_sum.json"))[key] for s, _ in SIZES]
        cells = " & ".join((f"\\textbf{{{x['bound']:.1f}\\%}}" if key == "mase0" else f"{x['bound']:.1f}\\%") for x in r)
        rows.append(f"{name} & {f(r[1]['corr'], 3, True)} & {r[1]['r2']:.2f} & {cells} \\\\")
        if key in ("horizstd", "ctxmae", "dryfrac"):
            o.num(f"rob{key.capitalize()}", f"{min(x['bound'] for x in r):.1f}--{max(x['bound'] for x in r):.1f}")
        if key == "dryfrac":
            o.num("rsqDry", f"{100 * r[1]['r2']:.0f}")
    o.table("robust", "\\begin{tabular}{lrrrrrr}\n\\toprule\ncovariate & corr.\\ with CE & $R^2$ & 20M & "
            "46M & 201M & 709M \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")

    # ------------------------------------------------------------------ power
    pw = json.load(open(FILES / "power_chronos-t5-small.json"))
    o.num("mdeAuc", f"{pw['auc/direct_vs_indirect']['mde_stn']:.3f}")
    mdes = [json.load(open(FILES / f"power_chronos-t5-{s}.json"))["gap/direct_vs_indirect/ce_sum"]["mde_pct"] for s, _ in SIZES]
    o.num("mdeGap", f"{min(mdes):.1f}" if round(min(mdes), 1) == round(max(mdes), 1) else f"{min(mdes):.1f}--{max(mdes):.1f}")

    # ------------------------------------------------------------------ cross-family control
    fc = json.load(open(FILES / "famcompare.json"))
    NAMES = {"chronos-mini": "Chronos 20M", "chronos-small": "Chronos 46M", "chronos-base": "Chronos 201M",
             "chronos-large": "Chronos 709M", "moirai-small": "Moirai small",
             "moirai-large": "Moirai large", "timesfm-200m": "TimesFM 200M", "timesfm-500m": "TimesFM 500M",
             "lagllama-base": "Lag-Llama"}
    rows = []
    for t, n in NAMES.items():
        r = fc[t]
        rows.append(f"{n} & {'yes' if r['in_corpus'] else 'no'} & ${r['raw']:+.3f}\\ [{r['raw_ci'][0]:.3f},\\ {r['raw_ci'][1]:.3f}]$ & "
                    f"${r['adj']:+.3f}\\ [{r['adj_ci'][0]:.3f},\\ {r['adj_ci'][1]:.3f}]$ \\\\")
    dd_ = fc["did"]
    rows += ["\\midrule", f"Chronos minus the others & & ${dd_['raw_est_sd']:+.3f}\\ [{dd_['raw_ci_sd'][0]:.3f},\\ {dd_['raw_ci_sd'][1]:.3f}]$ & ${dd_['est_sd']:+.3f}\\ [{dd_['ci_sd'][0]:.3f},\\ {dd_['ci_sd'][1]:.3f}]$ \\\\"]
    o.table("did", "\\begin{tabular}{llrr}\n\\toprule\nmodel & USHCN in corpus & raw gap & adjusted gap \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    o.num("didSd", f"{dd_['est_sd']:.3f}".replace("-", "$-$"))
    o.num("didSdLo", f"{dd_['ci_sd'][0]:.3f}".replace("-", "$-$")); o.num("didSdHi", f"{dd_['ci_sd'][1]:.3f}")
    p = dd_["pct_of_ce_46m"]
    o.num("didPct", f"{p[0]:.1f}".replace("-", "$-$")); o.num("didPctLo", f"{p[1]:.1f}".replace("-", "$-$"))
    o.num("didPctHi", f"{p[2]:.1f}"); o.num("didBound", f"{dd_['bound_pct_46m']:.1f}")
    q = dd_["raw_pct_of_ce_46m"]
    o.num("rawDidSd", f"{dd_['raw_est_sd']:.3f}"); o.num("rawDidSdLo", f"{dd_['raw_ci_sd'][0]:.3f}")
    o.num("rawDidSdHi", f"{dd_['raw_ci_sd'][1]:.3f}"); o.num("rawDidPct", f"{q[0]:.1f}")
    o.num("rawDidPctLo", f"{q[1]:.1f}"); o.num("rawDidPctHi", f"{q[2]:.1f}"); o.num("rawDidBound", f"{dd_['raw_bound_pct_46m']:.1f}")
    r2 = [fc[t]["r2_d"] for t in NAMES]
    o.num("rsqTimesfm", f"{fc['timesfm-200m']['r2_d']:.2f}")
    others = [fc[t]["r2_d"] for t in NAMES if not t.startswith("timesfm")]
    o.num("rsqOthers", f"{min(others):.2f}--{max(others):.2f}")

    # ------------------------------------------------------------------ planted grid, Chronos 46M
    z = np.load(OUT / "inject_delta_ep10.npz", allow_pickle=True)
    nc = int(z["n_core"]); d_core, d_clean = z["delta"][:nc], z["delta"][nc:]
    base, p95 = d_clean.mean(), np.percentile(d_clean, 95)
    o.num("ctrlMean", f"{base:.2f}"); o.num("ctrlSd", f"{d_clean.std(ddof=1):.2f}")
    bonf = 0.05 / 18
    o.num("bonf", f"{bonf:.4f}")
    short, full = [], []
    for t in TYPES:
        med, mean, share, pv, star = [], [], [], [], []
        for k in KS:
            m = (z["core_type"] == t) & (z["core_k"] == k)
            v = d_core[m]
            pp = float(stats.ttest_ind(v, d_clean, equal_var=False).pvalue)
            ex = v.mean() - base
            s_ = int((v > p95).sum())
            mean.append(ex); med.append(np.median(v) - base); share.append(s_ / 10); pv.append(pp)
            star.append(pp < bonf and ex > 0)
            if t == "verbatim" and k == 2:
                o.num("pExactTwenty", f"{pp:.3f}")
                hi = np.sort(v - base)[-2:]
                o.num("outlierA", f"{hi[0]:.0f}"); o.num("outlierB", f"{hi[1]:.0f}")
                o.num("seCellTwenty", f"{(v - base).std(ddof=1) / math.sqrt(10):.1f}")
            if t == "verbatim" and k == 4:
                o.num("pExactForty", sci(pp))
            if t == "mixup" and k == 32:
                o.num("blendMeanTop", f"{ex:.1f}"); o.num("pBlendTop", f"{pp:.2f}")
            if t == "mixup" and k == 2:
                o.num("pBlendTwenty", f"{pp:.3f}")
        med_s = " & ".join(f"${x:.1f}^\\star$" if s else f"${x:.1f}$" for x, s in zip(med, star))
        name = FORM[t]
        short.append(f"\\multirow{{2}}{{*}}{{{name}}} & median & {med_s} \\\\\n & share & "
                     + " & ".join(f"{x:.2f}" for x in share) + " \\\\")
        full.append(f"\\multirow{{4}}{{*}}{{{name}}} & median & " + " & ".join(f"${x:.1f}$" for x in med) + " \\\\\n"
                    + " & mean & " + " & ".join(f"${x:.1f}$" for x in mean) + " \\\\\n"
                    + " & share & " + " & ".join(f"{x:.2f}" for x in share) + " \\\\\n"
                    + " & $p$ & " + " & ".join(sci(x) for x in pv) + " \\\\")
        if t == "verbatim":
            o.num("exactMedLo", f"{med[0]:.1f}".replace("-", "$-$")); o.num("exactMedHi", f"{med[-1]:.1f}")
    head = "\\begin{tabular}{llrrrrrr}\n\\toprule\n & exposures & 10 & 20 & 40 & 80 & 160 & 320 \\\\\n\\midrule\n"
    o.table("inject", head + "\n\\midrule\n".join(short) + "\n\\bottomrule\n\\end{tabular}")
    o.table("inject_full", "\\begin{tabular}{llrrrrrr}\n\\toprule\nform & & $k{=}1$ & $k{=}2$ & $k{=}4$ & "
            "$k{=}8$ & $k{=}16$ & $k{=}32$ \\\\\n\\midrule\n"
            + "\n\\midrule\n".join(full) + "\n\\bottomrule\n\\end{tabular}")
    # relative excess in CE units, for the alignment with the bound
    ce_core = z["ce_before"][:nc].mean()
    for k, nm in ((1, "Ten"), (2, "Twenty")):
        m = (z["core_type"] == "verbatim") & (z["core_k"] == k)
        o.num(f"relExcess{nm}", f"{100 * (d_core[m].mean() - base) / ce_core:.1f}")

    # ------------------------------------------------------------------ family thresholds
    th = json.load(open(FILES / "family_thresholds.json"))
    lr = {"Chronos 46M": "$10^{-4}$", "Chronos 709M": "$10^{-4}$", "TimesFM 200M": "$10^{-5}$",
          "TimesFM 500M": "$10^{-5}$", "Moirai small": "$10^{-5}$", "Lag-Llama": "$10^{-4}$"}
    src = {"Chronos 46M": "chronos-small", "Chronos 709M": "chronos-large", "TimesFM 200M": "timesfm-200m",
           "TimesFM 500M": "timesfm-500m", "Moirai small": "moirai-small", "Lag-Llama": "lagllama"}
    SHOW = {"TimesFM 200M": "TimesFM 1.0-200M", "TimesFM 500M": "TimesFM 2.0-500M"}
    pe = {"Chronos 709M": "chronos-large (per epoch)", "TimesFM 200M": "timesfm-200m (per epoch)"}
    def cell(r, form):
        b, w_ = r["binom"][form], r["welch"][form]
        bs = "---" if b == "-" else str(b); ws = "---" if w_ == "-" else str(w_)
        return bs if bs == ws else f"{bs} ({ws})"
    rows = []
    for n, key in src.items():
        r = th[key]
        blend = cell(r, "mixup") + ("$^{\\dagger}$" if key == "lagllama" else "")
        extra = cell(th[pe[n]], "verbatim") if n in pe else ""
        rows.append(f"{SHOW.get(n, n)} & {lr[n]} & {cell(r, 'verbatim')} & {cell(r, 'variant')} & {blend} & {extra} \\\\")
    o.table("family", "\\begin{tabular}{llrrrr}\n\\toprule\nmodel & learning rate & exact & near-duplicate & "
            "blend & exact, scored each epoch \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")

    # ------------------------------------------------------------------ Moirai rescored with point losses
    # The prose names the one passing cell (blends, absolute error); the asserts keep it from drifting.
    mp = json.load(open(FILES / "family_moirai-small-point.json"))
    assert mp["reproduces"]["max_abs_diff"] < 1e-4, "retrained Moirai does not reproduce the reported run"
    hits = [(n, c, v) for n in ("mae", "pinball", "sqpin") for c, v in mp[n]["cells"].items()
            if v["frac"] >= 0.4 or v["readable_bonf"]]          # share test: four or more of ten
    assert [(n, c.split("/")[0]) for n, c, _ in hits] == [("mae", "mixup")], hits
    v = hits[0][2]
    WORD = {4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}
    o.num("moiraiPtHitDose", str(v["exposures"]))
    o.num("moiraiPtHitCores", WORD[round(10 * v["frac"])])
    o.num("moiraiPtHitP", f"{v['p']:.2f}")

    # ------------------------------------------------------------------ detectors
    de = json.load(open(FILES / "detect.json"))
    DN = {"loss": "loss", "min-k": "Min-20\\%", "diff-cal": "difficulty-calibrated", "ref-cal": "reference-calibrated"}
    rows = []
    for k_, n in DN.items():
        b = [de[f"benchmark/chronos-{s}"][k_] for s in ("small", "large")]
        pl = de["planted/chronos-small"]
        rows.append(f"{n} & {b[0]['auroc']:.3f} $[{b[0]['ci'][0]:.2f},\\ {b[0]['ci'][1]:.2f}]$ & "
                    f"{b[1]['auroc']:.3f} $[{b[1]['ci'][0]:.2f},\\ {b[1]['ci'][1]:.2f}]$ & "
                    f"{pl[f'{k_}/verbatim/k2']:.2f} & {pl[f'{k_}/verbatim/k32']:.2f} & {pl[f'{k_}/mixup/k32']:.2f} \\\\")
    o.table("detect", "\\begin{tabular}{lrrrrr}\n\\toprule\n& \\multicolumn{2}{c}{benchmark: direct vs.\\ indirect} & "
            "\\multicolumn{3}{c}{planted vs.\\ never planted (46M)} \\\\\n\\cmidrule(lr){2-3}\\cmidrule(lr){4-6}\n"
            "score & 46M & 709M & exact, 20 & exact, 320 & blend, 320 \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}")
    allb = [de[f"benchmark/chronos-{s}"][k_]["auroc"] for s in ("small", "large") for k_ in DN]
    o.num("detLo", f"{min(allb):.2f}"); o.num("detHi", f"{max(allb):.2f}")
    o.num("refBlendTop", f"{de['planted/chronos-small']['ref-cal/mixup/k32']:.2f}")
    o.num("refExactTwenty", f"{de['planted/chronos-small']['ref-cal/verbatim/k2']:.2f}")

    # ------------------------------------------------------------------ probe (one run: the dose sweep)
    pr = json.load(open(FILES / "probe.json"))
    sw, gr = pr["control_sweep"], pr["groups_n10"]
    ms = lambda v: f"{1e3 * v[0]:.3f} $\\pm$ {1e3 * v[1]:.3f}"
    rows = [f"exact, $k{{=}}{k}$ & {ms(sw[f'k{k}']['move'])}" for k in (32, 16, 8, 4, 2, 1)]
    rows.append(f"never planted & {ms(sw['held_out']['move'])}")
    right = [f"{g} & {ms(gr[g]['move'])}" for g in GROUPS] + [" & "] * 4
    body = "\n".join(f"{a} & {b} \\\\" for a, b in zip(rows, right))
    o.table("probe", "\\begin{tabular}{lrlr}\n\\toprule\n\\multicolumn{2}{c}{planted checkpoint} & "
            "\\multicolumn{2}{c}{released checkpoint} \\\\\n\\cmidrule(lr){1-2}\\cmidrule(lr){3-4}\n"
            "dose & movement & group & movement \\\\\n\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}")
    o.num("probeTop", f"{1e3 * sw['k32']['move'][0]:.2f}")
    o.num("probeHeld", f"{1e3 * sw['held_out']['move'][0]:.2f}")
    o.num("probeRatio", f"{sw['held_out']['move'][0] / sw['k32']['move'][0]:.1f}")
    for g in GROUPS:
        o.num(f"probe{g.capitalize()}", f"{1e3 * gr[g]['move'][0]:.2f}")
        o.num(f"probeSd{g.capitalize()}", f"{1e3 * gr[g]['move'][1]:.2f}")
    o.num("probeSdHeld", f"{1e3 * sw['held_out']['move'][1]:.2f}"); o.num("probeKone", f"{1e3 * sw['k1']['move'][0]:.2f}")
    o.num("probeSdKone", f"{1e3 * sw['k1']['move'][1]:.2f}")
    # ------------------------------------------------------------------ models
    fam = json.load(open(FILES / "famcompare.json"))
    LOSS = {"chronos": "token cross-entropy", "moirai": "NLL (mixture)", "timesfm": "squared + pinball",
            "lagllama": "NLL (Student-$t$)"}
    MODELS = [("Chronos", "chronos", [("mini", "20M"), ("small", "46M"), ("base", "201M"), ("large", "709M")]),
              ("Moirai 1.0-R", "moirai", [("small", "small"), ("large", "large")]),
              ("TimesFM", "timesfm", [("200m", "1.0-200M"), ("500m", "2.0-500M")]),
              ("Lag-Llama", "lagllama", [("base", "one size")])]
    PLANTED = {"chronos-small", "chronos-large", "moirai-small", "timesfm-200m", "timesfm-500m", "lagllama-base"}
    UNSTABLE = {"timesfm-200m": 1e-5, "timesfm-500m": 1e-5}     # stability amendment, see lr_check.py
    def lrtex(x):
        return "---" if x is None else {1e-4: "$10^{-4}$", 3e-5: "$3{\\times}10^{-5}$", 1e-5: "$10^{-5}$"}[x]
    rows = []
    for fname, fk, sizes in MODELS:
        for j, (sz, lab) in enumerate(sizes):
            tag = f"{fk}-{sz}"
            member = "yes" if fk == "chronos" else "no"
            if tag in PLANTED:
                lr_ = UNSTABLE.get(tag, json.load(open(FILES / f"lr_{tag}.json"))["chosen"]); lr_s = lrtex(lr_)
            elif (FILES / f"lr_{tag}.json").exists():
                lr_s = "no stable rate"
            else:
                lr_s = "not planted"
            rows.append(f"{fname if j == 0 else ''} & {lab} & {LOSS[fk] if j == 0 else ''} & {member} & {lr_s} \\\\")
        if fk != "lagllama":
            rows.append("\\midrule")
    o.table("models", "\\begin{tabular}{lllll}\n\\toprule\nfamily & checkpoint & training loss & USHCN in corpus & "
            "planted-data learning rate \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    o.close()
    print("tables:", sorted(p.name for p in Path(outdir).glob("*.tex")))


